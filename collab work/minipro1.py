    IQR = Q3 - Q1

    lower = Q1 - 1.5 * IQR
    upper = Q3 + 1.5 * IQR

    count = ((df[column] < lower) | (df[column] > upper)).sum()

    outlier_summary.append({
        "Feature": column,
        "Outliers": count,
        "Lower_Bound": lower,
        "Upper_Bound": upper
    })

